// Export single tank snapshot + history to Google Sheets (as XLSX download)
const exportSingleTankToSheets = async ({ tank, history, generatedBy }) => {
  try {
    const sheets = getSheets();
    const spreadsheetId = getSpreadsheetId();

    // ── Sheet1: Tank snapshot ─────────────────────────────────────────────────
    const snapshotHeaders = [
      [`PetroVault — Tank Report: ${tank.name}`],
      [`Generated by: ${generatedBy} | Date: ${formatDate(new Date())}`],
      [],
      ['Tank Name', 'Shape', 'Product', 'Current Volume (L)', 'Capacity (L)', 'Fill %', 'Status', 'Location', 'Low Threshold', 'High Threshold', 'Last Updated']
    ];
    const snapshotRow = [
      tank.name,
      tank.shape?.replace(/_/g, ' '),
      tank.product_name || 'N/A',
      tank.current_volume || 0,
      tank.capacity_litres,
      `${tank.fill_percentage}%`,
      tank.status?.toUpperCase() || 'UNKNOWN',
      tank.location || 'N/A',
      `${tank.low_threshold}%`,
      `${tank.high_threshold}%`,
      formatDate(tank.updated_at)
    ];
    await sheets.spreadsheets.values.update({
      spreadsheetId,
      range: 'Sheet1!A1',
      valueInputOption: 'RAW',
      resource: { values: [...snapshotHeaders, snapshotRow] }
    });

    // ── Sheet2: Transaction history ───────────────────────────────────────────
    const histHeaders = [
      [`PetroVault — Transaction History: ${tank.name}`],
      [`Generated by: ${generatedBy} | Date: ${formatDate(new Date())}`],
      [],
      ['Date & Time', 'Action', 'Volume Changed (L)', 'Volume Before (L)', 'Volume After (L)', 'Fill % Before', 'Fill % After', 'Recorded By', 'Notes']
    ];
    const histRows = history.map(h => [
      formatDate(h.created_at),
      h.action === 'add_stock' ? 'ADDED' : 'REMOVED',
      h.volume_changed || 0,
      h.volume_before || 0,
      h.volume_after || 0,
      `${h.fill_percentage_before}%`,
      `${h.fill_percentage_after}%`,
      h.recorded_by_name || 'N/A',
      h.notes || ''
    ]);
    await sheets.spreadsheets.values.update({
      spreadsheetId,
      range: 'Sheet2!A1',
      valueInputOption: 'RAW',
      resource: { values: [...histHeaders, ...histRows] }
    });

    // Format headers — fetch ALL sheet IDs in ONE API call
    const sheetIds = await getAllSheetIds(sheets, spreadsheetId, ['Sheet1', 'Sheet2']);
    const s1Id = sheetIds['Sheet1'];
    const s2Id = sheetIds['Sheet2'];
    await sheets.spreadsheets.batchUpdate({
      spreadsheetId,
      resource: {
        requests: [
          { repeatCell: { range: { sheetId: s1Id, startRowIndex: 0, endRowIndex: 1, startColumnIndex: 0, endColumnIndex: 11 }, cell: { userEnteredFormat: { backgroundColor: { red: 0.12, green: 0.16, blue: 0.24 }, textFormat: { bold: true, fontSize: 14, foregroundColor: { red: 1, green: 1, blue: 1 } } } }, fields: 'userEnteredFormat(backgroundColor,textFormat)' } },
          { repeatCell: { range: { sheetId: s1Id, startRowIndex: 3, endRowIndex: 4, startColumnIndex: 0, endColumnIndex: 11 }, cell: { userEnteredFormat: { backgroundColor: { red: 0.49, green: 0.23, blue: 0.93 }, textFormat: { bold: true, foregroundColor: { red: 1, green: 1, blue: 1 } } } }, fields: 'userEnteredFormat(backgroundColor,textFormat)' } },
          { repeatCell: { range: { sheetId: s2Id, startRowIndex: 0, endRowIndex: 1, startColumnIndex: 0, endColumnIndex: 9 }, cell: { userEnteredFormat: { backgroundColor: { red: 0.12, green: 0.16, blue: 0.24 }, textFormat: { bold: true, fontSize: 14, foregroundColor: { red: 1, green: 1, blue: 1 } } } }, fields: 'userEnteredFormat(backgroundColor,textFormat)' } },
          { repeatCell: { range: { sheetId: s2Id, startRowIndex: 3, endRowIndex: 4, startColumnIndex: 0, endColumnIndex: 9 }, cell: { userEnteredFormat: { backgroundColor: { red: 0.49, green: 0.23, blue: 0.93 }, textFormat: { bold: true, foregroundColor: { red: 1, green: 1, blue: 1 } } } }, fields: 'userEnteredFormat(backgroundColor,textFormat)' } },
          { autoResizeDimensions: { dimensions: { sheetId: s1Id, dimension: 'COLUMNS', startIndex: 0, endIndex: 11 } } },
          { autoResizeDimensions: { dimensions: { sheetId: s2Id, dimension: 'COLUMNS', startIndex: 0, endIndex: 9 } } }
        ]
      }
    });

    // Download as xlsx
    const auth = getAuth();
    const tokenResponse = await auth.getAccessToken();
    const accessToken = tokenResponse.token;
    const url = `https://docs.google.com/spreadsheets/d/${spreadsheetId}/export?format=xlsx`;
    const response = await fetch(url, { headers: { Authorization: `Bearer ${accessToken}` } });
    if (!response.ok) throw new Error(`Failed to fetch spreadsheet: ${response.statusText}`);
    const arrayBuffer = await response.arrayBuffer();
    const buffer = Buffer.from(arrayBuffer);
    return { success: true, buffer };

  } catch (error) {
    console.error('❌ Single tank Sheets export failed:', error.message);
    return { success: false, error: error.message };
  }
};

