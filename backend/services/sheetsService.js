const { google } = require('googleapis');
require('dotenv').config();

const cleanEnv = (val) => val?.trim().replace(/^["']|["']$/g, '');

// Create Google Sheets auth
const getAuth = () => {
  return new google.auth.JWT({
    email: cleanEnv(process.env.GOOGLE_SHEETS_CLIENT_EMAIL),
    key: cleanEnv(process.env.GOOGLE_SHEETS_PRIVATE_KEY)?.replace(/\\n/g, '\n'),
    scopes: [
      'https://www.googleapis.com/auth/spreadsheets',
      'https://www.googleapis.com/auth/drive.readonly'
    ]
  });
};

const getSpreadsheetId = () => cleanEnv(process.env.GOOGLE_SHEETS_SPREADSHEET_ID);

// Get sheets instance
const getSheets = () => {
  const auth = getAuth();
  return google.sheets({ version: 'v4', auth });
};

// Get real sheetId by tab name (single lookup)
const getSheetId = async (sheets, spreadsheetId, sheetName) => {
  const meta = await sheets.spreadsheets.get({ spreadsheetId });
  const sheet = meta.data.sheets.find(
    s => s.properties.title === sheetName
  );
  if (!sheet) throw new Error(`Sheet tab "${sheetName}" not found in spreadsheet`);
  return sheet.properties.sheetId;
};

// Get multiple sheet IDs in ONE API call — avoids redundant round trips
const getAllSheetIds = async (sheets, spreadsheetId, sheetNames) => {
  const meta = await sheets.spreadsheets.get({ spreadsheetId });
  const map = {};
  for (const name of sheetNames) {
    const found = meta.data.sheets.find(s => s.properties.title === name);
    if (!found) throw new Error(`Sheet tab "${name}" not found in spreadsheet`);
    map[name] = found.properties.sheetId;
  }
  return map;
};

// Format date for sheets
const formatDate = (date) => {
  return new Date(date).toLocaleString('en-IN', {
    timeZone: 'Asia/Kolkata'
  });
};

// Export tank data to Google Sheets
const exportTanksToSheets = async ({ tanks, generatedBy }) => {
  try {
    const sheets = getSheets();
    const spreadsheetId = getSpreadsheetId();

    // Prepare header row
    const headers = [
      ['PetroVault — Tank Status Report'],
      [`Generated by: ${generatedBy} | Date: ${formatDate(new Date())}`],
      [],
      [
        'Tank Name',
        'Shape',
        'Product',
        'Current Volume (L)',
        'Capacity (L)',
        'Fill %',
        'Status',
        'Location',
        'Last Updated'
      ]
    ];

    // Prepare data rows
    const rows = tanks.map(tank => [
      tank.name,
      tank.shape,
      tank.product_name || 'N/A',
      tank.current_volume || 0,
      tank.capacity_litres,
      `${tank.fill_percentage}%`,
      tank.status?.toUpperCase() || 'UNKNOWN',
      tank.location || 'N/A',
      formatDate(tank.updated_at)
    ]);

    const allRows = [...headers, ...rows];

    // Write to sheet
    await sheets.spreadsheets.values.update({
      spreadsheetId,
      range: 'Sheet1!A1',
      valueInputOption: 'RAW',
      resource: { values: allRows }
    });

    // Format header row — bold and colored
    const sheet1Id = await getSheetId(sheets, spreadsheetId, 'Sheet1');
    await sheets.spreadsheets.batchUpdate({
      spreadsheetId,
      resource: {
        requests: [
          // Title row formatting
          {
            repeatCell: {
              range: { sheetId: sheet1Id, startRowIndex: 0, endRowIndex: 1, startColumnIndex: 0, endColumnIndex: 9 },
              cell: {
                userEnteredFormat: {
                  backgroundColor: { red: 0.12, green: 0.16, blue: 0.24 },
                  textFormat: { bold: true, fontSize: 14, foregroundColor: { red: 1, green: 1, blue: 1 } }
                }
              },
              fields: 'userEnteredFormat(backgroundColor,textFormat)'
            }
          },
          // Column header row formatting
          {
            repeatCell: {
              range: { sheetId: sheet1Id, startRowIndex: 3, endRowIndex: 4, startColumnIndex: 0, endColumnIndex: 9 },
              cell: {
                userEnteredFormat: {
                  backgroundColor: { red: 0.49, green: 0.23, blue: 0.93 },
                  textFormat: { bold: true, foregroundColor: { red: 1, green: 1, blue: 1 } }
                }
              },
              fields: 'userEnteredFormat(backgroundColor,textFormat)'
            }
          },
          // Auto resize columns
          {
            autoResizeDimensions: {
              dimensions: { sheetId: sheet1Id, dimension: 'COLUMNS', startIndex: 0, endIndex: 9 }
            }
          }
        ]
      }
    });

    console.log('✅ Exported to Google Sheets successfully, now downloading...');

    // Download spreadsheet as xlsx
    const auth = getAuth();
    const tokenResponse = await auth.getAccessToken();
    const accessToken = tokenResponse.token;

    const url = `https://docs.google.com/spreadsheets/d/${spreadsheetId}/export?format=xlsx`;
    const response = await fetch(url, {
      headers: {
        Authorization: `Bearer ${accessToken}`
      }
    });

    if (!response.ok) {
      throw new Error(`Failed to fetch spreadsheet: ${response.statusText}`);
    }

    const arrayBuffer = await response.arrayBuffer();
    const buffer = Buffer.from(arrayBuffer);

    console.log('✅ Exported to Google Sheets and downloaded as xlsx successfully');
    return { success: true, buffer };

  } catch (error) {
    console.error('❌ Google Sheets export failed:', error.message);
    return { success: false, error: error.message };
  }
};

