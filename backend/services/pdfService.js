const PDFDocument = require('pdfkit');
const { getFillColor, getTankStatus } = require('../utils/tankShapeHelper');

const STATUS_STYLE = {
  empty:    { bg: '#f1f5f9', text: '#0f172a', label: 'EMPTY' },
  critical: { bg: '#fef2f2', text: '#ef4444', label: 'CRITICAL' },
  warning:  { bg: '#fefce8', text: '#ca8a04', label: 'WARNING' },
  healthy:  { bg: '#f0fdf4', text: '#16a34a', label: 'HEALTHY' },
};

const renderPdfBuffer = (buildFn) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 40 });
    const chunks = [];
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    buildFn(doc);
    doc.end();
  });
};

const drawHeader = (doc, title) => {
  doc.rect(40, 40, 32, 32).fill('#7c3aed');
  doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(15).text('PV', 44, 49, { width: 24, align: 'center' });

  doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(20).text('PetroVault', 82, 40);
  doc.fillColor('#64748b').font('Helvetica').fontSize(10).text(`Oil Tank Management System — ${title}`, 82, 62);

  doc.fillColor('#64748b').fontSize(9).text(`Generated: ${new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' })}`, 360, 50, {
    width: 195,
    align: 'right',
  });

  doc.moveTo(40, 82).lineTo(555, 82).lineWidth(2).strokeColor('#7c3aed').stroke();
  doc.y = 96;
};

const drawInfoCards = (doc, items) => {
  const startX = 40;
  const gap = 8;
  const width = (515 - gap * (items.length - 1)) / items.length;
  const y = doc.y;

  items.forEach((item, idx) => {
    const x = startX + idx * (width + gap);
    doc.roundedRect(x, y, width, 44, 6).fillAndStroke(item.bg || '#f8fafc', item.border || '#e2e8f0');
    doc.fillColor(item.labelColor || '#94a3b8').font('Helvetica-Bold').fontSize(7.5).text(item.label.toUpperCase(), x + 8, y + 8, { width: width - 16 });
    doc.fillColor(item.valueColor || '#0f172a').font('Helvetica-Bold').fontSize(11).text(String(item.value), x + 8, y + 21, { width: width - 16, ellipsis: true });
  });

  doc.y = y + 58;
};

const drawTable = (doc, columns, rows) => {
  const startX = 40;
  const tableWidth = columns.reduce((s, c) => s + c.width, 0);

  const drawRowHeader = (y) => {
    doc.rect(startX, y, tableWidth, 24).fill('#7c3aed');
    let x = startX;
    columns.forEach((col) => {
      doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(8).text(col.label.toUpperCase(), x + 6, y + 8, {
        width: col.width - 12,
        ellipsis: true,
      });
      x += col.width;
    });
    return y + 24;
  };

  let y = drawRowHeader(doc.y);

  if (rows.length === 0) {
    doc.fillColor('#94a3b8').font('Helvetica').fontSize(10).text('No records found.', startX, y + 12);
    doc.y = y + 32;
    return;
  }

  rows.forEach((row, idx) => {
    if (y > 760) {
      doc.addPage();
      y = drawRowHeader(40);
    }

    if (idx % 2 === 1) {
      doc.rect(startX, y, tableWidth, 22).fill('#f8fafc');
    }

    let x = startX;
    columns.forEach((col, cIdx) => {
      const cell = row[cIdx];
      const text = typeof cell === 'object' && cell !== null ? cell.text : cell;
      const color = typeof cell === 'object' && cell !== null && cell.color ? cell.color : '#0f172a';
      const bold = typeof cell === 'object' && cell !== null && cell.bold;
      doc
        .fillColor(color)
        .font(bold ? 'Helvetica-Bold' : 'Helvetica')
        .fontSize(8.5)
        .text(String(text ?? ''), x + 6, y + 7, { width: col.width - 12, ellipsis: true });
      x += col.width;
    });

    doc.moveTo(startX, y + 22).lineTo(startX + tableWidth, y + 22).lineWidth(0.5).strokeColor('#e2e8f0').stroke();
    y += 22;
  });

  doc.y = y + 14;
};

const drawFooter = (doc) => {
  if (doc.y > 770) doc.addPage();
  const y = Math.max(doc.y + 10, 780);
  doc.moveTo(40, y).lineTo(555, y).lineWidth(0.5).strokeColor('#e2e8f0').stroke();
  doc.fillColor('#94a3b8').font('Helvetica').fontSize(8).text('Generated by PetroVault Oil Tank Management System', 40, y + 8, {
    width: 515,
    align: 'center',
  });
};

// ─── Tanks / History PDF ──────────────────────────────────────────────────────

const generatePDF = async ({ title, tanks = [], dateRange, generatedBy }) => {
  try {
    const isHistoryReport = tanks.length > 0 && tanks[0].tank_name !== undefined && tanks[0].action !== undefined;

    const buffer = await renderPdfBuffer((doc) => {
      drawHeader(doc, title || 'Tank Status Report');

      if (isHistoryReport) {
        drawInfoCards(doc, [
          { label: 'Report Period', value: dateRange || 'All Time' },
          { label: 'Generated By', value: generatedBy || 'System' },
          { label: 'Total Records', value: tanks.length, bg: '#ede9fe', border: '#ddd6fe', labelColor: '#7c3aed', valueColor: '#7c3aed' },
        ]);

        const columns = [
          { label: 'Date & Time', width: 95 },
          { label: 'Tank', width: 55 },
          { label: 'Product', width: 70 },
          { label: 'Action', width: 65 },
          { label: 'Changed', width: 65 },
          { label: 'Fill After', width: 55 },
          { label: 'By', width: 110 },
        ];

        const rows = tanks.map((h) => [
          new Date(h.created_at).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata', dateStyle: 'short', timeStyle: 'short' }),
          { text: h.tank_name, bold: true },
          h.product_name || 'N/A',
          {
            text: h.action === 'add_stock' ? 'ADDED' : 'REMOVED',
            bold: true,
            color: h.action === 'add_stock' ? '#16a34a' : '#ca8a04',
          },
          `${h.action === 'add_stock' ? '+' : '-'}${(h.volume_changed || 0).toLocaleString()} L`,
          `${h.fill_percentage_after ?? 0}%`,
          h.recorded_by_name || 'System',
        ]);

        drawTable(doc, columns, rows);
      } else {
        const totalVolume = tanks.reduce((s, t) => s + (t.current_volume || 0), 0);
        const totalCapacity = tanks.reduce((s, t) => s + (t.capacity_litres || 0), 0);
        const overallFill = totalCapacity > 0 ? Math.round((totalVolume / totalCapacity) * 1000) / 10 : 0;

        const healthyCount = tanks.filter((t) => getTankStatus(t.fill_percentage) === 'healthy').length;
        const warningCount = tanks.filter((t) => getTankStatus(t.fill_percentage) === 'warning').length;
        const criticalCount = tanks.filter((t) => getTankStatus(t.fill_percentage) === 'critical').length;
        const emptyCount = tanks.filter((t) => getTankStatus(t.fill_percentage) === 'empty').length;

        drawInfoCards(doc, [
          { label: 'Report Period', value: dateRange || 'Today' },
          { label: 'Generated By', value: generatedBy || 'System' },
          { label: 'Total Tanks', value: tanks.length },
          { label: 'Overall Fill', value: `${overallFill}%`, bg: '#ede9fe', border: '#ddd6fe', labelColor: '#7c3aed', valueColor: '#7c3aed' },
        ]);

        drawInfoCards(doc, [
          { label: 'Healthy', value: healthyCount, bg: '#f0fdf4', border: '#bbf7d0', labelColor: '#16a34a', valueColor: '#16a34a' },
          { label: 'Warning', value: warningCount, bg: '#fefce8', border: '#fde68a', labelColor: '#ca8a04', valueColor: '#ca8a04' },
          { label: 'Critical', value: criticalCount, bg: '#fef2f2', border: '#fecaca', labelColor: '#ef4444', valueColor: '#ef4444' },
          { label: 'Empty', value: emptyCount, bg: '#f8fafc', border: '#e2e8f0', labelColor: '#64748b', valueColor: '#0f172a' },
        ]);

        const columns = [
          { label: 'Tank', width: 65 },
          { label: 'Shape', width: 95 },
          { label: 'Product', width: 85 },
          { label: 'Current Vol', width: 80 },
          { label: 'Capacity', width: 75 },
          { label: 'Fill %', width: 50 },
          { label: 'Status', width: 65 },
        ];

        const rows = tanks.map((tank) => {
          const status = getTankStatus(tank.fill_percentage);
          const color = getFillColor(status);
          return [
            { text: tank.name, bold: true },
            (tank.shape || '').replace(/_/g, ' '),
            tank.product_name || 'N/A',
            `${(tank.current_volume || 0).toLocaleString()} L`,
            `${(tank.capacity_litres || 0).toLocaleString()} L`,
            { text: `${tank.fill_percentage}%`, bold: true, color },
            { text: status.toUpperCase(), bold: true, color },
          ];
        });

        drawTable(doc, columns, rows);
      }

      drawFooter(doc);
    });

    return { success: true, buffer };
  } catch (error) {
    console.error('PDF generation failed:', error.message);
    return { success: false, error: error.message };
  }
};

// ─── Single Tank Detailed PDF ─────────────────────────────────────────────────

const generateSingleTankPDF = async ({ tank, history = [], generatedBy }) => {
  try {
    const sc = STATUS_STYLE[tank.status] || STATUS_STYLE.healthy;
    const totalAdded = history.filter((h) => h.action === 'add_stock').reduce((s, h) => s + (h.volume_changed || 0), 0);
    const totalRemoved = history.filter((h) => h.action === 'remove_stock').reduce((s, h) => s + (h.volume_changed || 0), 0);

    const buffer = await renderPdfBuffer((doc) => {
      drawHeader(doc, `Tank Report — ${tank.name}`);

      drawInfoCards(doc, [
        { label: 'Tank & Shape', value: `${tank.name} (${(tank.shape || '').replace(/_/g, ' ')})` },
        { label: 'Product', value: tank.product_name || 'N/A' },
        { label: 'Fill Level', value: `${tank.fill_percentage}%`, bg: '#ede9fe', border: '#ddd6fe', labelColor: '#7c3aed', valueColor: '#7c3aed' },
        { label: 'Status', value: sc.label, bg: sc.bg, border: '#e2e8f0', labelColor: sc.text, valueColor: sc.text },
      ]);

      drawInfoCards(doc, [
        { label: 'Current Volume', value: `${(tank.current_volume || 0).toLocaleString()} L` },
        { label: 'Capacity', value: `${(tank.capacity_litres || 0).toLocaleString()} L` },
        { label: 'Total Added (90d)', value: `+${totalAdded.toLocaleString()} L`, bg: '#f0fdf4', border: '#bbf7d0', labelColor: '#16a34a', valueColor: '#16a34a' },
        { label: 'Total Removed (90d)', value: `-${totalRemoved.toLocaleString()} L`, bg: '#fefce8', border: '#fde68a', labelColor: '#ca8a04', valueColor: '#ca8a04' },
      ]);

      doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(12).text(`Transaction History (last ${history.length} transactions)`, 40, doc.y);
      doc.moveDown(0.5);

      const columns = [
        { label: 'Date & Time', width: 95 },
        { label: 'Action', width: 65 },
        { label: 'Vol Change', width: 75 },
        { label: 'Fill Change', width: 85 },
        { label: 'By', width: 80 },
        { label: 'Notes', width: 115 },
      ];

      const rows = history.map((h) => [
        new Date(h.created_at).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata', dateStyle: 'short', timeStyle: 'short' }),
        {
          text: h.action === 'add_stock' ? 'ADDED' : 'REMOVED',
          bold: true,
          color: h.action === 'add_stock' ? '#16a34a' : '#ca8a04',
        },
        `${h.action === 'add_stock' ? '+' : '-'}${(h.volume_changed || 0).toLocaleString()} L`,
        `${h.fill_percentage_before}% -> ${h.fill_percentage_after}%`,
        h.recorded_by_name || 'System',
        h.notes || '-',
      ]);

      drawTable(doc, columns, rows);
      drawFooter(doc);
    });

    return { success: true, buffer };
  } catch (error) {
    console.error('Single tank PDF generation failed:', error.message);
    return { success: false, error: error.message };
  }
};

module.exports = { generatePDF, generateSingleTankPDF };
